import {test,expect} from '@playwright/test'
import fs from 'node:fs'
import path from 'node:path'

const output=path.resolve('../storage/screenshots')
fs.mkdirSync(output,{recursive:true})

test('knowledge editor autosaves, previews math and retains versioned data',async({page,request})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  const response=await request.post('/api/objects',{data:{kind:'concept',title:'浏览器验收：动作表示',tags:['验收']}})
  expect(response.ok()).toBeTruthy();const object=await response.json()
  await page.goto(`/knowledge/${object.id}`)
  await page.getByRole('button',{name:'编辑',exact:true}).click()
  await page.getByLabel('笔记标题').fill('动作表示：已保存的理解')
  await page.getByLabel('笔记正文').fill('# 动作与坐标系\n\n中文笔记，策略为 $a_t = \\pi(o_t)$。\n\n```python\naction = policy(observation)\n```')
  await expect(page.locator('.save-status')).toHaveText('已保存',{timeout:15000})
  await page.reload()
  await expect(page.getByLabel('笔记标题')).toHaveValue('动作表示：已保存的理解')
  await page.getByRole('button',{name:'阅读',exact:true}).click()
  await expect(page.locator('.katex').first()).toBeVisible()
  await expect(page.locator('.markdown')).toContainText('动作与坐标系')
  await page.screenshot({path:path.join(output,'note.png'),fullPage:true})
  expect(errors).toEqual([])
})

test('canvas connects and edits local edges, groups cards, persists layout and undo',async({page,request})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  const a=await (await request.post('/api/objects',{data:{kind:'model',title:'画布验收模型'}})).json()
  const b=await (await request.post('/api/objects',{data:{kind:'concept',title:'画布验收概念'}})).json()
  const canvas=await (await request.post('/api/canvases',{data:{title:'浏览器验收画布'}})).json()
  const idA=crypto.randomUUID(),idB=crypto.randomUUID()
  await request.put(`/api/canvases/${canvas.id}/document`,{data:{title:canvas.title,version:1,viewport:{x:0,y:0,zoom:1},items:[{id:idA,item_type:'object',object_id:a.id,x:45,y:120,width:260,height:155},{id:idB,item_type:'object',object_id:b.id,x:380,y:120,width:260,height:155}],edges:[]}})
  await page.goto(`/canvases/${canvas.id}`)
  await expect(page.locator('.react-flow__node')).toHaveCount(2)
  const handleA=await page.locator(`[data-id="${idA}"] .react-flow__handle.source`).boundingBox()
  const handleB=await page.locator(`[data-id="${idB}"] .react-flow__handle.target`).boundingBox()
  await page.mouse.move(handleA.x+handleA.width/2,handleA.y+handleA.height/2)
  await page.mouse.down();await page.mouse.move(handleB.x+handleB.width/2,handleB.y+handleB.height/2,{steps:12});await page.mouse.up()
  await expect(page.locator('.react-flow__edge')).toHaveCount(1)
  await expect(page.locator('.save-status')).toHaveText('已保存',{timeout:15000})
  let stored=await (await request.get(`/api/canvases/${canvas.id}`)).json()
  expect(stored.edges).toHaveLength(1);expect(stored.edges[0].relation_id).toBeNull()
  await page.mouse.click((handleA.x+handleB.x)/2,handleA.y+handleA.height/2)
  await page.getByLabel('显示文字').fill('待验证的联系')
  await page.getByLabel('联系说明').fill('通过浏览器验收建立的关系')
  await page.getByRole('button',{name:'保存为知识关系'}).click()
  await expect(page.locator('.canvas-inspector')).toContainText('引用正式知识关系')
  await expect(page.locator('.save-status')).toHaveText('已保存',{timeout:15000})
  stored=await (await request.get(`/api/canvases/${canvas.id}`)).json()
  expect(stored.edges[0].relation_id).toBeTruthy()
  const nodeA=page.locator(`[data-id="${idA}"]`)
  const position=await nodeA.boundingBox()
  await page.mouse.move(position.x+80,position.y+65);await page.mouse.down();await page.mouse.move(position.x+130,position.y+120,{steps:10});await page.mouse.up()
  await expect(page.locator('.save-status')).toHaveText('已保存',{timeout:15000})
  const afterDrag=await (await request.get(`/api/canvases/${canvas.id}`)).json()
  expect(afterDrag.items.find(i=>i.id===idA).x).not.toBe(45)
  await page.getByRole('button',{name:'撤销',exact:true}).click()
  await expect(page.locator('.save-status')).toHaveText('已保存',{timeout:15000})
  const undone=await (await request.get(`/api/canvases/${canvas.id}`)).json()
  expect(undone.items.find(i=>i.id===idA).x).toBe(45)
  await page.reload();await expect(page.locator('.react-flow__node')).toHaveCount(2)
  await page.locator(`[data-id="${idA}"] strong`).click()
  await page.locator(`[data-id="${idB}"] strong`).click({modifiers:['Shift']})
  await page.getByRole('button',{name:'组合选中卡片'}).click()
  await expect(page.locator('.react-flow__node')).toHaveCount(3)
  await expect(page.locator('.save-status')).toHaveText('已保存',{timeout:15000})
  const grouped=await (await request.get(`/api/canvases/${canvas.id}`)).json()
  expect(grouped.items.filter(i=>i.parent_id)).toHaveLength(2)
  await page.reload();await expect(page.locator('.react-flow__node')).toHaveCount(3)
  await page.screenshot({path:path.join(output,'canvas.png'),fullPage:true})
  expect(errors).toEqual([])
})

